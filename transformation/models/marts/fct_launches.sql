{{
    config(
        materialized = "table",
        partition_by = {
            "field": "net",
            "data_type": "timestamp",
            "granularity": "year",
        },
        cluster_by = ["agency_sector", "agency_country", "orbit_regime"],
    )
}}

with enriched_launches as (
    select
        launch_id,
        launch_name,
        last_updated,
        net,
        window_start,
        window_end,
        launch_date,
        launch_year,
        launch_quarter,
        status_name,
        status_abbrev,
        fail_reason,
        agency_id,
        agency_name,
        agency_type,
        agency_sector,
        agency_country,
        rocket_id,
        rocket_name,
        mission_name,
        mission_type,
        orbit_name,
        orbit_abbrev,
        orbit_regime,
        pad_id,
        pad_name,
        location_name,
        latitude,
        longitude,
        pad_total_launches,
        prev_pad_launch_net,
        pad_turnaround_hours,
        pad_turnaround_days,
        prev_rocket_launch_net,
        vehicle_turnaround_hours,
        window_duration_seconds,
        window_duration_mins,
        is_instantaneous_window,
        window_duration_bucket,
        liftoff_slip_seconds,
        liftoff_slip_mins,
        window_consumed_pct,
        is_t0_on_time,
        is_anomaly,
        is_launch_failure
    from {{ ref('int_launches__enriched') }}
),

fleet_counts as (
    select
        *,
        count(launch_id) over (partition by rocket_name) as vehicle_launch_count,
        count(launch_id) over () as global_launch_count
    from enriched_launches
)

select
    launch_id,
    launch_name,
    last_updated,
    net,
    window_start,
    window_end,
    launch_date,
    launch_year,
    launch_quarter,
    status_name,
    status_abbrev,
    fail_reason,
    agency_id,
    agency_name,
    agency_type,
    agency_sector,
    agency_country,
    rocket_id,
    rocket_name,
    mission_name,
    mission_type,
    orbit_name,
    orbit_abbrev,
    orbit_regime,
    pad_id,
    pad_name,
    location_name,
    latitude,
    longitude,
    pad_total_launches,
    prev_pad_launch_net,
    pad_turnaround_hours,
    pad_turnaround_days,
    prev_rocket_launch_net,
    vehicle_turnaround_hours,
    window_duration_seconds,
    window_duration_mins,
    is_instantaneous_window,
    window_duration_bucket,
    liftoff_slip_seconds,
    liftoff_slip_mins,
    window_consumed_pct,
    is_t0_on_time,
    is_anomaly,
    is_launch_failure,
    vehicle_launch_count,
    global_launch_count,
    round(
        100.0 * safe_divide(vehicle_launch_count, global_launch_count),
        2
    ) as vehicle_concentration_pct
from fleet_counts
